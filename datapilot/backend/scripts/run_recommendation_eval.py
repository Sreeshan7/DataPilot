"""Measure the final recommendation on the graded benchmark and write a report.

    python -m scripts.run_recommendation_eval

Offline and deterministic: no network, no credentials, no timestamps in the output,
so two runs on the same code write identical files. Exit code 1 only when a safety
rule is violated (an incompatible best match, or an AI suggestion recommended).
"""

from __future__ import annotations

import sys
from pathlib import Path

BACKEND_ROOT = Path(__file__).resolve().parent.parent
if str(BACKEND_ROOT) not in sys.path:
    sys.path.insert(0, str(BACKEND_ROOT))

from app.core.config import Settings  # noqa: E402
from app.services.datasets.evaluation.benchmark import load_benchmark  # noqa: E402
from app.services.datasets.evaluation.recommendation_benchmark import (  # noqa: E402
    CaseVerdict,
    compare_with_rank_one,
    evaluate_recommendations,
)

OUTPUT = BACKEND_ROOT / "evaluation"


def main() -> int:
    settings = Settings(
        gemini_api_key="",
        kaggle_api_token="",
        kaggle_enabled=False,
        dataset_discovery_genai_enabled=False,
        app_env="testing",
    )
    report = evaluate_recommendations(load_benchmark(), settings)
    comparison = compare_with_rank_one(report)

    (OUTPUT / "recommendation_results.json").write_text(
        report.model_dump_json(indent=2) + "\n", encoding="utf-8"
    )

    lines = [
        "# Final-recommendation evaluation",
        "",
        "Generated by `python -m scripts.run_recommendation_eval`. Offline and deterministic.",
        "Measured on the project's own hand-graded corpus (62 cases); this is **not** real-world",
        "accuracy.",
        "",
        "## Metrics",
        "",
        "| metric | value |",
        "| --- | --- |",
        *[f"| {k} | {v} |" for k, v in report.metrics.items()],
        "",
        "## Verdict counts",
        "",
        *[f"- {k}: {v}" for k, v in report.counts.items()],
        "",
        f"Rescued relative to taking rank 1: {', '.join(comparison.rescued) or 'none'}",
        f"Harmed relative to taking rank 1: {', '.join(comparison.harmed) or 'none'}",
        "",
        "## Cases that were not simply correct",
        "",
        "| case | verdict | outcome | best grade | pool best |",
        "| --- | --- | --- | --- | --- |",
        *[
            f"| {r.case_id} | {r.verdict} | {r.outcome.value} | {r.best_grade} | {r.pool_best_grade} |"
            for r in report.cases
            if r.verdict != CaseVerdict.CORRECT
        ],
        "",
    ]
    (OUTPUT / "RECOMMENDATION_EVALUATION.md").write_text("\n".join(lines), encoding="utf-8")

    print(report.metrics)
    print(report.counts)
    if report.safety_violations:
        print("SAFETY VIOLATIONS:", report.safety_violations)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
