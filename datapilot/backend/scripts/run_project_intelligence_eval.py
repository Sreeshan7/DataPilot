"""Measure Phase 5 project intelligence on the curated benchmark and write a report.

    python -m scripts.run_project_intelligence_eval

Offline and deterministic (seeded data, production importance settings, no network, no Gemini, no
timestamps in the output). Exit code 1 only when a safety rule is violated: an invented column, a
leaking column recommended, or a goal matched to a dataset that contradicts it.
"""

from __future__ import annotations

import sys
from pathlib import Path

BACKEND_ROOT = Path(__file__).resolve().parent.parent
if str(BACKEND_ROOT) not in sys.path:
    sys.path.insert(0, str(BACKEND_ROOT))

from app.services.dataset_analysis.evaluation.project_benchmark import (  # noqa: E402
    ProjectBenchmarkReport,
    run_project_benchmark,
)

OUTPUT = BACKEND_ROOT / "evaluation"


def render(report: ProjectBenchmarkReport) -> str:
    lines = [
        "# Project intelligence evaluation", "",
        "Generated by `python -m scripts.run_project_intelligence_eval`. Offline and deterministic.",
        "Measured on seeded synthetic datasets where the true drivers, noise columns and leaks are known",
        "from how they were generated. **Not** real-world accuracy.", "",
        "## Metrics", "", "| metric | value |", "| --- | --- |",
        *[f"| {k} | {v} |" for k, v in report.metrics.items()], "",
        "## Per dataset", "",
        "| dataset | model beat baseline | ideas | recommended features | problems |", "| --- | --- | --- | --- | --- |",
    ]
    for r in report.datasets:
        problems = "; ".join(filter(None, [
            f"noise recommended: {', '.join(r.noise_recommended)}" if r.noise_recommended else "",
            f"strong drivers missed: {', '.join(r.drivers_missed)}" if r.drivers_missed else "",
            f"leaks missed: {', '.join(r.leaks_missed)}" if r.leaks_missed else "",
            f"invented columns: {', '.join(r.invented_columns)}" if r.invented_columns else "",
        ])) or "none"
        lines.append(f"| {r.name} | {r.reliable} | {r.ideas} | {', '.join(r.recommended[:6]) or '-'} | {problems} |")
    lines += ["", "## Goal compatibility misses", "", *(f"- {m}" for m in report.goal_misses or ["none"]),
              "", "## Safety rules", "", *([f"- VIOLATED: {v}" for v in report.safety_violations] or ["- none violated"]),
              "", "## How to read this", "",
              "- `wide_numeric` hides two real drivers among 118 pure-noise columns. A small number of noise",
              "  columns being recommended is the measurable cost of testing 40 columns at once; it is reported,",
              "  not hidden (`noise_recommended`).",
              "- A goal-compatibility miss found by this benchmark (an input named in the goal but absent from the",
              "  data still produced MATCH) was fixed: such a goal now stops at UNKNOWN.",
              "- Gemini is not exercised here: ideas are the deterministic ones, and the optional prose layer is",
              "  covered by validation tests with a fake writer.", ""]
    return "\n".join(lines)


def main() -> int:
    report = run_project_benchmark()
    (OUTPUT / "project_intelligence_results.json").write_text(report.model_dump_json(indent=2) + "\n", encoding="utf-8")
    (OUTPUT / "PROJECT_INTELLIGENCE_EVALUATION.md").write_text(render(report), encoding="utf-8")
    for key, value in report.metrics.items():
        print(f"{key:30s} {value}")
    for violation in report.safety_violations:
        print("VIOLATION:", violation)
    return 1 if report.safety_violations else 0


if __name__ == "__main__":
    raise SystemExit(main())
