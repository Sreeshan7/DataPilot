"""Measure dataset analysis and journey routing on the curated benchmark and write a report.

    python -m scripts.run_dataset_analysis_eval

Offline and deterministic: seeded synthetic datasets, no network, no credentials, no timestamps
in the output, so two runs on the same code write identical files (also under different
``PYTHONHASHSEED`` values). Exit code 1 only when a safety rule is violated: a STRONG target
claimed where none exists, a task offered that the data cannot support, or a request sent to the
wrong journey.
"""

from __future__ import annotations

import sys
from pathlib import Path

BACKEND_ROOT = Path(__file__).resolve().parent.parent
if str(BACKEND_ROOT) not in sys.path:
    sys.path.insert(0, str(BACKEND_ROOT))

from app.services.dataset_analysis.evaluation.benchmark import (  # noqa: E402
    BenchmarkReport,
    run_benchmark,
)

OUTPUT = BACKEND_ROOT / "evaluation"


def _problems(result) -> str:
    parts = []
    if result.target_top1_correct is False:
        parts.append(f"wrong target ({result.best_target})")
    for label, values in (
        ("tasks missing", result.tasks_missing), ("unsupported task", result.tasks_forbidden_present),
        ("identifiers missed", result.identifiers_missed), ("false identifiers", result.identifiers_false),
        ("sensitive missed", result.sensitive_missed), ("findings missed", result.findings_missed),
        ("false alarms", result.forbidden_findings_present), ("free text missed", result.free_text_missed),
    ):
        if values:
            parts.append(f"{label}: {', '.join(values)}")
    if result.strong_target_when_none_exists:
        parts.append("claimed a STRONG target where none exists")
    return "; ".join(parts) or "none"


def render(report: BenchmarkReport) -> str:
    lines = [
        "# Dataset analysis and routing evaluation",
        "",
        "Generated by `python -m scripts.run_dataset_analysis_eval`. Offline and deterministic.",
        "Measured on the project's own seeded synthetic datasets and hand-written routing phrasings;",
        "this is **not** real-world accuracy. See *How to read this* below.",
        "",
        "## Metrics",
        "",
        "| metric | value |",
        "| --- | --- |",
        *[f"| {key} | {value} |" for key, value in report.metrics.items()],
        "",
        "## Per-dataset results",
        "",
        "| dataset | held out | rows | best target | state | problems |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for r in report.datasets:
        lines.append(
            f"| {r.name} | {'yes' if r.heldout else 'no'} | {r.rows} | {r.best_target or '-'} | "
            f"{r.target_state or '-'} | {_problems(r)} |")
    lines += ["", "## Routing misses", ""]
    groups = (
        ("tuned cases", report.routing_misses), ("held-out round 1", report.heldout_routing_misses),
        ("round 2", report.round2_routing_misses), ("unseen (measured once, not tuned)", report.unseen_routing_misses),
    )
    for label, misses in groups:
        lines.append(f"- {label}: " + (
            ", ".join(f"#{m.index} expected {m.expected} got {m.got}" for m in misses) if misses else "none"))
    lines += [
        "",
        "## Safety rules",
        "",
        *(f"- VIOLATED: {v}" for v in report.safety_violations),
        *(["- none violated"] if not report.safety_violations else []),
        "",
        "## How to read this",
        "",
        "- The twelve *tuned* datasets were used while the analyzer's rules were written, so a perfect",
        "  score on them shows the rules agree with what was planted, not that they generalise.",
        "- The three *held-out* datasets had their expectations fixed before the first run. The first run",
        "  exposed a real false alarm (a strongly separating feature was reported as leakage), which was",
        "  fixed; they are therefore no longer untouched.",
        "- Routing is rule-based. Measured **before** any fix, the first held-out batch scored 0.68 with one",
        "  wrong-journey error and the second 0.667 with one; both were fixed and now score 1.0 (in-sample).",
        "  The *unseen* batch was measured once and not tuned: 0.65, no wrong journey. Every miss there was",
        "  AMBIGUOUS, i.e. a question to the user, never a wrong turn. That 0.65 is the honest estimate of",
        "  how often a new phrasing resolves without a question.",
        "- External-only datasets (a name or link) are tested for honesty in `test_dataset_analysis_benchmark.py`:",
        "  they must never carry statistics, quality findings, parsed evidence or an overstated target.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    report = run_benchmark()
    (OUTPUT / "dataset_analysis_results.json").write_text(
        report.model_dump_json(indent=2) + "\n", encoding="utf-8")
    (OUTPUT / "DATASET_ANALYSIS_EVALUATION.md").write_text(render(report), encoding="utf-8")
    for key, value in report.metrics.items():
        print(f"{key:48s} {value}")
    if report.safety_violations:
        print("\nSAFETY VIOLATIONS")
        for violation in report.safety_violations:
            print(" -", violation)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
