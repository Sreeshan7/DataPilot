// Regenerates src/types/api.ts from the backend's own OpenAPI schema, so the UI's types cannot drift from
// the contracts the backend actually serves.   Usage: npm run gen:api   (needs the backend venv)
import { execFileSync } from "node:child_process";
import { writeFileSync, readFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const backend = resolve(here, "../../backend");
const python = join(backend, ".venv", process.platform === "win32" ? "Scripts/python.exe" : "bin/python");
const spec = join(mkdtempSync(join(tmpdir(), "datapilot-openapi-")), "openapi.json");
const code = "import json,sys;from app.main import app;json.dump(app.openapi(),open(sys.argv[1],'w'))";
execFileSync(python, ["-c", code, spec], { cwd: backend, stdio: "inherit", env: { ...process.env, PYTHONPATH: backend } });
const out = resolve(here, "../src/types/api.ts");
execFileSync(process.execPath, [resolve(here, "../node_modules/openapi-typescript/bin/cli.js"), spec, "-o", out], { stdio: "inherit" });
writeFileSync(out, "// GENERATED by scripts/gen-api.mjs from the backend OpenAPI schema. Do not edit by hand.\n" + readFileSync(out, "utf8"));
console.log("wrote", out);
